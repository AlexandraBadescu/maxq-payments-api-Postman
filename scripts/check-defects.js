'use strict';

// Run each seeded defect separately and check that the expected
// scenario fails. A green suite isn't useful if it misses known bugs.
const fs = require('node:fs');
const path = require('node:path');
const { DEFECTS } = require('../src/defects');
const { ROOT, runSuite, failedChecks } = require('./lib/runSuite');

// Scenario number that must catch each defect.
const EXPECTED = {
  'auth-not-required': '15',
  'ownership-not-checked': '16',
  'declined-payment-captured': '13',
  'double-payment-allowed': '14',
  'captured-on-request': '01',
  'capture-timeout-missing': '11',
  'late-capture-rejected': '12',
  'duplicate-events-reapplied': '07',
  'out-of-order-event-applied': '09',
  'refund-limit-ignored': '03',
  'refund-before-capture-allowed': '04',
  'refunded-total-wrong': '01',
  'failed-refund-keeps-reservation': '06',
  'history-entry-missing': '01',
  'reservation-ignored-in-limit': '03',
  'capture-history-duplicated': '07',
  'order-ownership-not-checked': '23',
  'double-capture-allowed': '17',
  'login-accepts-any-password': '15',
  'declined-blocks-retry': '14',
  'quantity-not-validated': '21',
  'quantity-unbounded': '21',
  'null-item-crashes': '21',
  'email-not-unique': '22',
  'email-case-sensitive': '22',
  'weak-password-allowed': '22',
  'refund-reapplied-by-new-event': '19',
  'refunded-payment-refundable': '18',
  'rejected-event-consumes-id': '20',
  'ownership-leak-via-message': '24',
  'payment-wrong-currency': '01',
  'payment-wrong-order': '01',
};

// Defects that the setup guard itself is meant to catch. Every other defect must be
// caught by a check in the scenario's own steps, not by a setup step failing early:
// a broken setup would fail the scenario whatever the bug was.
const CAUGHT_IN_SETUP = new Set(['payment-wrong-currency', 'payment-wrong-order']);

async function main() {
  const missing = Object.keys(DEFECTS).filter((name) => !EXPECTED[name]);
  if (missing.length > 0) throw new Error(`No expected scenario for: ${missing.join(', ')}`);

  const clean = await runSuite();
  if (clean.run.failures.length > 0) {
    throw new Error('The suite fails with no defect switched on, so this check means nothing.');
  }

  const rows = [];
  for (const [name, description] of Object.entries(DEFECTS)) {
    const summary = await runSuite({ seededDefect: name });
    const failures = failedChecks(summary);
    const scenarios = [...new Set(failures.map((failure) => failure.scenario))];
    const inExpected = failures.filter((failure) => failure.scenario.startsWith(EXPECTED[name]));
    const decisive = inExpected.filter(
      (failure) => CAUGHT_IN_SETUP.has(name) || !failure.request.startsWith('Setup:'),
    );
    const caught = decisive.length > 0;
    const firstCheck = (decisive[0] ?? inExpected[0] ?? failures[0])?.check ?? 'none';
    rows.push({ name, description, caught, scenarios, firstCheck });
    console.log(
      `${caught ? 'CAUGHT' : 'MISSED'}  ${name}  ->  ${scenarios.join(' | ') || 'no failures'}  [${firstCheck}]`,
    );
  }

  const caughtCount = rows.filter((row) => row.caught).length;
  const number = (scenario) => scenario.slice(0, 2);
  const report = [
    '# Seeded defect results',
    '',
    'Generated by `npm run test:defects`. Each row is a full run of the suite against the service with one deliberate bug switched on.',
    '',
    `**${caughtCount} of ${rows.length} caught by the scenario meant to catch them.** A bug only counts as caught when a check in that scenario's own steps fails, not just a setup step. The suite also passed with no bug switched on.`,
    '',
    '| Deliberate bug | Caught? | Scenarios that failed | A check that failed in the expected scenario |',
    '|---|---|---|---|',
    ...rows.map(
      (row) =>
        `| ${row.description} | ${row.caught ? 'Yes' : '**No**'} | ${row.scenarios.map(number).join(', ') || 'None'} | ${row.firstCheck.replace(/\|/g, '/')} |`,
    ),
    '',
    'These are bugs I chose, so this shows the suite catches these failures. It does not show that the suite would catch every possible bug.',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(ROOT, 'docs', 'defect-results.md'), report);

  console.log(`\n${caughtCount} of ${rows.length} caught.`);
  process.exitCode = caughtCount === rows.length ? 0 : 1;
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
